// THE OPPOSITE SIDE OF EVERY PRINTED TWO-BRANCH PREDICATE, AS A FIXTURE.
//
//   node scratchpad/author-branch-fixtures.mjs <form> [--apply]
//
// ═══════════════════════════════════════════════════════════════════════════════════════
// WHY IT EXISTS
// ═══════════════════════════════════════════════════════════════════════════════════════
//
// 433-B(OIC) declares 31 total lines and its gate reports "28 checked, 3 skipped". 433-A(OIC)
// declares 51 and reports "49 checked, 2 skipped". THE SKIPPED ONES ARE SKIPPED ON EVERY
// FIXTURE EITHER FORM HAS — acceptance, stress, negative and all three record-shape fixtures,
// six runs each, the same lines skipped in all of them:
//
//   433boi   4a leased, 4b own, 4c leased
//   433aoi   6a leased, 6c own
//
// Each is one branch of a printed conditional. The vehicle tables print DIFFERENT arithmetic
// for a leased vehicle than for an owned one — a leased row contributes a printed constant of
// zero, an owned row contributes its quick-sale equity — so the map declares TWO total lines
// per printed cell, each with a `when` predicate on that row's lease_or_own. A fixture fixes
// each vehicle to one state, so it can only ever put one branch of each pair in class.
//
// A LINE NO FIXTURE PUTS IN CLASS CANNOT BE PROVED TO REFUSE. Breaking its total by a cent
// does nothing: the tripwire is never asked, the line reads "skipped", and a proof recording
// that would be recording nothing. So the input has to exist before the proof can.
//
// ═══════════════════════════════════════════════════════════════════════════════════════
// HOW THE TOTALS IN IT ARE OBTAINED — NOT TYPED, AND NOT A SECOND IMPLEMENTATION
// ═══════════════════════════════════════════════════════════════════════════════════════
//
// Flipping the flags makes every downstream total wrong, and there are two bad ways to fix
// that. Typing them is a typed count. Re-implementing the form's arithmetic here is a SECOND
// implementation of the thing the tripwires exist to check, and the two would agree with each
// other rather than with the page.
//
// So this file CONVERGES AGAINST THE GATE. It writes the flipped record, runs the real gate,
// reads the per-line result the gate itself writes, and copies each failing line's `recomputed`
// figure — the gate's own sum of the printed operands — back into the fixture. Repeat until no
// line fails. The authority is the same tool that will later be asked to refuse a one-cent
// break, and every figure in the finished fixture is one it computed.
//
// THE FIXTURE THEREFORE CLAIMS NO GENERATOR, and that is deliberate rather than an omission.
// adapters/pdf/validate-map.mjs runs the authorship assert at GATE STEP 3, and that assert
// RE-RUNS the generator any fixture names. A fixture naming this script would make every gate
// run spawn this script, which spawns the gate. The fixture declares instead, in its own body,
// how its figures were obtained and what the only difference from the acceptance record is.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { resolveFixture } from '../adapters/pdf/resolve-fixture.mjs';

const FORM = process.argv[2];
const APPLY = process.argv.includes('--apply');
if (!FORM) { console.error('usage: node scratchpad/author-branch-fixtures.mjs <form> [--apply]'); process.exit(2); }

// BOTH SIDES, AND THE SECOND ONE IS NOT A CONVENIENCE.
//
// The acceptance record already holds one side of every printed conditional, so one flipped
// fixture looks like enough. It is not: THE ACCEPTANCE RECORD IS UNSAFE TO BREAK. On 433-B(OIC)
// five other fixtures are generated by READING it off disk — the three record-shape fixtures,
// the negative and the stress one — and a break held in it makes all five stop matching the
// generator they name, taking the gate down at step 3 on files the prover never touched. So the
// three lines only that side puts in class had nowhere to be proved.
//
// `held` takes the same side as the acceptance record and `flipped` takes the other. Neither is
// any other fixture's input, so a break survives in both.
const SIDES = [
  { suffix: 'held', flip: false, why: 'the same side of every printed conditional the acceptance record takes' },
  { suffix: 'flipped', flip: true, why: 'the other side of every printed conditional' },
];
const MAX_ROUNDS = 12;

// --- the acceptance record, DISCOVERED ------------------------------------------------------
const res = resolveFixture(FORM, 'acceptance');
if (res.problems.length) { for (const p of res.problems) console.error(`STOP — ${p}`); process.exit(2); }
console.log(`acceptance fixture for ${FORM}: ${res.path}`);
const base = JSON.parse(readFileSync(res.path, 'utf8'));

// --- THE PREDICATE KEYS, DERIVED FROM THE TOTALS FILE ---------------------------------------
// Never a typed list of "the vehicle group". The totals file names, in each feeder's `when`
// clause, the exact key whose value decides the branch — "4ac_vehicles[0].lease_or_own" — and
// the two values it is tested against are the `equals` of the two branches of the same pair.
const totals = JSON.parse(readFileSync(`adapters/pdf/maps/${FORM}.totals.json`, 'utf8'));
const predicates = new Map();   // predicate key -> Set of values some declared line tests for
for (const t of totals.totals) {
  for (const fd of (t.feeders || [])) {
    if (!fd.when || typeof fd.when.key !== 'string') continue;
    if (!predicates.has(fd.when.key)) predicates.set(fd.when.key, new Set());
    predicates.get(fd.when.key).add(String(fd.when.equals));
  }
}
console.log(`declared two-branch predicates on ${FORM}: ${predicates.size}`);
for (const [k, vs] of predicates) console.log(`  ${k}  tested against {${[...vs].join(', ')}}`);
if (!predicates.size) { console.error(`STOP — ${FORM}.totals.json declares no \`when\` predicate, so it has no branch to take the other side of. A branch fixture for it would exercise nothing.`); process.exit(2); }

// --- read and write one "group[i].column" address in a record --------------------------------
//
// THE PREDICATE NAMES THE MAP'S GROUP, AND THE RECORD IS KEYED BY THE GROUP'S `source`. They
// are different names — "4ac_vehicles[0].lease_or_own" addresses a slot of the MAP group
// `4ac_vehicles`, whose rows come from the RECORD key `vehicles`. The first draft of this file
// looked the map name up in the record, found nothing, and STOPped saying the cell was absent;
// the cell was there under the name the map itself declares one line away. The translation is
// read from the map, never assumed to be identity.
const mapDoc = JSON.parse(readFileSync(`adapters/pdf/maps/${FORM}.map.json`, 'utf8'));
const ADDR = /^([A-Za-z0-9_]+)\[(\d+)\]\.([A-Za-z0-9_]+)$/;
const at = (doc, key) => {
  const m = ADDR.exec(key);
  if (!m) return null;
  const [, group, idx, col] = m;
  // A GROUP THAT DECLARES NO `source` IS KEYED IN THE RECORD BY ITS OWN NAME. Latent here
  // rather than live — every form carrying a `when` predicate declares one — and repaired in
  // the same commit as the prover, where the identical assumption was live on all sixteen of
  // [B-07]'s new lines and made the run STOP over a cell the gate had just reported verified.
  const src = mapDoc.groups?.[group]?.source ?? group;
  if (typeof src !== 'string') return null;
  const rows = doc[src];
  if (!Array.isArray(rows)) return null;
  const row = rows[Number(idx)];
  if (!row || typeof row !== 'object') return null;
  return { row, col, group, source: src, idx: Number(idx) };
};

// ─── ONE PASS PER SIDE ────────────────────────────────────────────────────────────────────
const written = [];
for (const SIDE of SIDES) {
const OUT = `samples/${FORM}.branch-${SIDE.suffix}.sample.json`;
  // --- flip every predicate cell to the branch the acceptance record does NOT take -------------
  const doc = JSON.parse(JSON.stringify(base));
  const flips = [];
  for (const [key, values] of predicates) {
    const vs = [...values];
    if (vs.length !== 2) { console.error(`STOP — predicate ${key} is tested against ${vs.length} value(s) {${vs.join(', ')}}. This file flips a TWO-branch predicate and cannot say what the other side of anything else is.`); process.exit(2); }
    const site = at(doc, key);
    if (!site) { console.error(`STOP — ${res.path} carries no cell at ${key}, so there is no branch to flip.`); process.exit(2); }
    const was = String(site.row[site.col] ?? '');
    const norm = was.trim().toLowerCase();
    const hit = vs.find((v) => String(v).trim().toLowerCase() === norm);
    if (!hit) { console.error(`STOP — ${key} holds ${JSON.stringify(was)}, which is neither of the two values the totals file tests it against {${vs.join(', ')}}. A cell in neither branch is not a cell this file can flip.`); process.exit(2); }
    // THE `held` SIDE KEEPS WHAT THE ACCEPTANCE RECORD HAS; THE `flipped` SIDE TAKES THE OTHER.
    const other = SIDE.flip ? vs.find((v) => v !== hit) : hit;
    site.row[site.col] = other;
    flips.push({ key, from: was, to: other });
  }
  console.log('');
  console.log(`${SIDE.suffix}: ${flips.length} predicate cell(s) set to ${SIDE.why}:`);
  for (const f of flips) console.log(`  ${f.key}  ${JSON.stringify(f.from)} -> ${JSON.stringify(f.to)}`);

  // --- the fixture's own declarations ----------------------------------------------------------
  delete doc._generated_by;
  delete doc._co_authored_with_hand;
  doc._fixture = {
    form: FORM,
    role: 'branch',
    branch_state: SIDE.suffix,
    why: `One member of ${FORM}'s BRANCH SET: the acceptance record with every declared two-branch predicate cell set to ${SIDE.why}. The set carries both sides because a record puts each printed conditional on ONE of them, and because THE ACCEPTANCE RECORD ITSELF IS UNSAFE TO BREAK — other fixtures are generated by reading it off disk, so a break held in it makes them drift from the generator they name and takes the gate down at step 3 on files nobody touched. Neither member of this set is anything else's input.`,
  };
  doc._what_is_different_from_the_acceptance_record = SIDE.flip
    ? flips.map((f) => `${f.key}: ${JSON.stringify(f.from)} -> ${JSON.stringify(f.to)}`)
    : 'NOTHING BUT THIS DECLARATION. Every predicate cell holds the value the acceptance record holds, and every total is the one the acceptance record carries. It exists because the acceptance record cannot be broken without other fixtures drifting from the generators they name, and a line only that side puts in class needs a record of its own to be proved in.';
  doc._how_every_total_in_here_was_obtained =
    'CONVERGED AGAINST THE GATE, not typed and not recomputed by a second implementation. '
    + 'scratchpad/author-branch-fixtures.mjs wrote the flipped record, ran adapters/pdf/run-form-gate.mjs against it, read the per-line result the gate writes to adapters/pdf/out/, and copied each failing line\'s `recomputed` figure — the gate\'s own sum of the printed operands — back into this file, repeating until no line failed. '
    + 'Every figure here is one the gate computed from the operands this record prints, and the gate re-derives all of them on every run.';
  doc._it_names_no_generator_on_purpose =
    'adapters/pdf/validate-map.mjs runs adapters/pdf/assert-fixture-authorship.mjs at GATE STEP 3, and that assert RE-RUNS the generator any fixture names. A `_generated_by` pointing at the script that authored this file would make every gate run spawn a script that spawns the gate. What the generator claim would have carried is written out above instead: the record it came from, the one class of change made to it, and how the figures were obtained.';

  // --- converge ---------------------------------------------------------------------------------
  const gate = () => {
    const r = spawnSync(process.execPath, ['adapters/pdf/run-form-gate.mjs', FORM, OUT, '--saturated'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    return { status: r.status, out: `${r.stdout || ''}${r.stderr || ''}` };
  };
  const tripwirePathFrom = (out) => {
    const line = out.split('\n').find((l) => l.includes('per-line result written to '));
    if (!line) return null;
    return line.split('per-line result written to ')[1].split(' ')[0].trim();
  };
  /** Match the decimal convention of whatever is already at that key. */
  const like = (existing, n) => {
    const s = String(existing ?? '');
    const dot = s.indexOf('.');
    const places = dot < 0 ? 0 : s.length - dot - 1;
    return n.toFixed(places);
  };

  writeFileSync(OUT, JSON.stringify(doc, null, 1) + '\n');
  console.log('');
  console.log(`wrote ${OUT} (flipped, totals not yet converged)`);

  let round = 0, lastFailed = null;
  for (; round < MAX_ROUNDS; round++) {
    const run = gate();
    const tp = tripwirePathFrom(run.out);
    if (!tp || !existsSync(tp)) {
      console.error(`STOP — round ${round + 1}: the gate did not reach step 11, so there is no per-line result to converge against. Exit ${run.status}.`);
      console.error(run.out.split('\n').filter((l) => /FAIL|STOP|GATE/.test(l)).slice(-12).join('\n'));
      process.exit(2);
    }
    const rep = JSON.parse(readFileSync(tp, 'utf8'));
    const failed = rep.lines.filter((l) => l.verdict === 'failed');
    const skipped = rep.lines.filter((l) => l.verdict === 'skipped');
    console.log(`round ${round + 1}: gate exit ${run.status} — ${rep.lines.length} line(s), ${failed.length} failed, ${skipped.length} skipped`);
    if (!failed.length) {
      console.log(`  CONVERGED after ${round} correction round(s). Skipped on this record: ${skipped.map((l) => l.line).join(', ') || 'none'}`);
      break;
    }
    // A STALL IS THE SAME LINES DISAGREEING THE SAME WAY, NOT THE SAME NUMBER OF THEM.
    //
    // The first draft compared `failed.length` and STOPped on round 3 of 433-B(OIC), where round
    // 2 failed line "4" and round 3 failed "Box A" — one line each, different lines, and the
    // second was the cascade of correcting the first. A totals graph converges from the leaves
    // up, so a per-round count sits flat while real progress is being made. The signature has to
    // be WHICH lines and by WHAT, and a repeat of that is a figure being recomputed away.
    const sig = failed.map((l) => `${l.line}|${l.printed}|${l.recomputed}`).sort().join(' ; ');
    if (sig === lastFailed) {
      console.error(`STOP — round ${round + 1} failed the same line(s), with the same figures, as the round before. Convergence has stalled; a figure this file writes is being recomputed away.`);
      for (const l of failed) console.error(`  ${l.line}: printed ${l.printed}, recomputed ${l.recomputed}`);
      process.exit(2);
    }
    lastFailed = sig;
    // A DECLARED TOTAL IS ADDRESSED TWO WAYS AND BOTH ARE HANDLED BY NAME.
    //
    //   key:<total_key>                     a top-level scalar in the record
    //   cell:<group>.<column>#<row>         a cell of a repeatable group's row
    //
    // The three lines this fixture exists for are ALL of the second kind — "4a leased" is the
    // printed Total cell of vehicle slot 0, not a scalar — so a converger that only knew the
    // first would have STOPped on exactly the lines it was written to reach.
    const CELL = /^cell:([A-Za-z0-9_]+)\.([A-Za-z0-9_]+)#(\d+)$/;
    for (const l of failed) {
      const addr = String(l.addr || '');
      if (addr.startsWith('key:')) {
        const key = addr.slice(4);
        if (!(key in doc)) { console.error(`STOP — the record carries no key ${key} for line ${l.line}.`); process.exit(2); }
        const was = doc[key];
        doc[key] = like(was, l.recomputed);
        console.log(`  ${String(l.line).padEnd(11)} ${key} ${JSON.stringify(was)} -> ${JSON.stringify(doc[key])}  (the gate's own sum of the printed operands)`);
        continue;
      }
      const m = CELL.exec(addr);
      if (!m) { console.error(`STOP — line ${l.line} is addressed as ${JSON.stringify(addr)}, which is neither "key:<k>" nor "cell:<group>.<column>#<row>". This file cannot write its figure into the record.`); process.exit(2); }
      const [, group, col, idx] = m;
      const src = mapDoc.groups?.[group]?.source ?? group;
      if (typeof src !== 'string') { console.error(`STOP — the map declares no \`source\` for group ${group} and its own name is not usable as a record key, so line ${l.line}'s cell has no address in the record.`); process.exit(2); }
      const row = (doc[src] || [])[Number(idx)];
      if (!row || typeof row !== 'object') { console.error(`STOP — the record's ${src}[${idx}] is not a row, so line ${l.line}'s cell cannot be written.`); process.exit(2); }
      const was = row[col];
      row[col] = like(was, l.recomputed);
      console.log(`  ${String(l.line).padEnd(11)} ${src}[${idx}].${col} ${JSON.stringify(was)} -> ${JSON.stringify(row[col])}  (the gate's own reading of what this row's branch prints)`);
    }
    writeFileSync(OUT, JSON.stringify(doc, null, 1) + '\n');
  }
  if (round === MAX_ROUNDS) { console.error(`STOP — did not converge in ${MAX_ROUNDS} rounds.`); process.exit(2); }

  if (!APPLY) {
    console.log('');
    console.log(`DRY RUN — ${OUT} was written and converged so the result could be read, and it is left in place for inspection.`);
    console.log('Re-run with --apply to keep it and print the summary this commit records.');
    written.push({ path: OUT, side: SIDE.suffix, rounds: round, flips: flips.length });
    continue;
  }
  console.log('');
  written.push({ path: OUT, side: SIDE.suffix, rounds: round, flips: flips.length });
  console.log(`APPLIED — ${OUT}`);
  console.log(`  role "branch", branch_state ${SIDE.suffix}; ${flips.length} predicate cell(s) set; converged in ${round} correction round(s).`);

}

console.log('');
console.log(`${written.length} branch fixture(s) for ${FORM}: ${written.map((w) => `${w.path} (${w.side}, ${w.rounds} correction round(s))`).join(', ')}`);